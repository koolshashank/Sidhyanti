import { PoweroffOutlined } from '@ant-design/icons';
import { Alert, Button, DatePicker, Form, Input, InputNumber, Modal, Select, Table, Tag, message } from 'antd';
import type { ColumnsType } from 'antd/es/table';
import dayjs, { type Dayjs } from 'dayjs';
import { useEffect, useState } from 'react';
import { fetchBillingStatus, generateBillingInvoice, toggleServices, type BillingInvoice } from '../api/billing';
import { apiErrorMessage } from '../api/client';
import { AppShell } from '../layouts/AppShell';
import { fdate, money } from '../utils/format';

interface FormShape {
  periodType: 'Monthly' | 'Quarterly' | 'Yearly';
  periodStart: Dayjs;
  amount: number;
  notes?: string;
}

export default function BillingPage() {
  const [servicesEnabled, setServicesEnabled] = useState<boolean | null>(null);
  const [invoices, setInvoices] = useState<BillingInvoice[]>([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);
  const [toggling, setToggling] = useState(false);
  const [form] = Form.useForm<FormShape>();
  const [generating, setGenerating] = useState(false);

  function load() {
    setLoading(true);
    fetchBillingStatus()
      .then((res) => {
        setServicesEnabled(res.servicesEnabled);
        setInvoices(res.invoices);
      })
      .catch((err) => setError(apiErrorMessage(err)))
      .finally(() => setLoading(false));
  }

  useEffect(load, []);

  function handleToggle() {
    const enable = !servicesEnabled;
    Modal.confirm({
      title: enable ? 'Re-enable this CRM for everyone?' : 'Disable this CRM for everyone except SuperAdmin?',
      content: enable
        ? 'Everyone will be able to log in and use the web CRM and mobile app again.'
        : 'This stops the web CRM (except SuperAdmin) and the mobile app for everyone, immediately.',
      okButtonProps: { danger: !enable },
      onOk: async () => {
        setToggling(true);
        try {
          await toggleServices(enable);
          message.success('Service status updated');
          load();
        } catch (err) {
          message.error(apiErrorMessage(err));
        } finally {
          setToggling(false);
        }
      },
    });
  }

  async function handleGenerate() {
    const values = await form.validateFields();
    setGenerating(true);
    try {
      await generateBillingInvoice({
        periodType: values.periodType,
        periodStart: values.periodStart.format('YYYY-MM-DD'),
        amount: values.amount,
        notes: values.notes,
      });
      message.success('Billing generated');
      form.resetFields();
      load();
    } catch (err) {
      message.error(apiErrorMessage(err));
    } finally {
      setGenerating(false);
    }
  }

  const columns: ColumnsType<BillingInvoice> = [
    { title: 'Period', dataIndex: 'periodType' },
    { title: 'Start', dataIndex: 'periodStart', render: (v) => fdate(v) },
    { title: 'End', dataIndex: 'periodEnd', render: (v) => fdate(v) },
    { title: 'Amount', dataIndex: 'amount', render: (v: number) => money(v) },
    { title: 'Notes', dataIndex: 'notes', render: (v) => v ?? '-' },
    { title: 'Generated By', dataIndex: 'generatedByName', render: (v) => v ?? '-' },
    { title: 'Generated At', dataIndex: 'createdAt', render: (v) => fdate(v) },
  ];

  if (error) {
    return (
      <AppShell title="Billing">
        <Alert type="error" message={error} showIcon />
      </AppShell>
    );
  }

  return (
    <AppShell title="Billing">
      <div className="flex flex-col gap-6">
        <div className="rounded-2xl border border-slate-100 bg-white p-5 shadow-sm">
          <div className="flex flex-wrap items-center justify-between gap-4">
            <div>
              <h3 className="text-base font-semibold text-slate-800">Service Status</h3>
              <p className="text-sm text-slate-500">
                Disabling stops the web CRM (except SuperAdmin) and the mobile app for everyone, immediately.
              </p>
            </div>
            <div className="flex items-center gap-3">
              {servicesEnabled !== null && (
                <Tag color={servicesEnabled ? 'success' : 'error'} className="px-3 py-1 text-sm">
                  {servicesEnabled ? '● Enabled' : '● Disabled'}
                </Tag>
              )}
              <Button
                danger={!!servicesEnabled}
                type={servicesEnabled ? 'default' : 'primary'}
                icon={<PoweroffOutlined />}
                loading={toggling}
                disabled={loading}
                onClick={handleToggle}
              >
                {servicesEnabled ? 'Disable Service' : 'Re-enable Service'}
              </Button>
            </div>
          </div>
        </div>

        <div className="rounded-2xl border border-slate-100 bg-white p-5 shadow-sm">
          <h3 className="mb-4 text-base font-semibold text-slate-800">Generate Billing</h3>
          <Form<FormShape> form={form} layout="inline" onFinish={handleGenerate} className="flex flex-wrap gap-3">
            <Form.Item name="periodType" rules={[{ required: true, message: 'Required' }]} initialValue="Monthly">
              <Select
                style={{ width: 140 }}
                options={[
                  { value: 'Monthly', label: 'Monthly' },
                  { value: 'Quarterly', label: 'Quarterly' },
                  { value: 'Yearly', label: 'Yearly' },
                ]}
              />
            </Form.Item>
            <Form.Item name="periodStart" rules={[{ required: true, message: 'Required' }]} initialValue={dayjs()}>
              <DatePicker format="DD MMM YYYY" placeholder="Period Start" />
            </Form.Item>
            <Form.Item name="amount" rules={[{ required: true, message: 'Required' }]}>
              <InputNumber min={0.01} step={0.01} placeholder="Amount" style={{ width: 150 }} />
            </Form.Item>
            <Form.Item name="notes">
              <Input placeholder="Notes (optional)" style={{ width: 220 }} maxLength={255} />
            </Form.Item>
            <Form.Item>
              <Button type="primary" htmlType="submit" loading={generating}>
                Generate
              </Button>
            </Form.Item>
          </Form>
        </div>

        <div className="rounded-2xl border border-slate-100 bg-white p-5 shadow-sm">
          <h3 className="mb-4 text-base font-semibold text-slate-800">Billing History</h3>
          <Table<BillingInvoice> rowKey="billingId" columns={columns} dataSource={invoices} loading={loading} pagination={false} />
        </div>
      </div>
    </AppShell>
  );
}
